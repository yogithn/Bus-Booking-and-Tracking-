function normalizeCityName(city) {
  return String(city || '').trim().toLowerCase().replace(/[^a-z0-9]/g, '');
}

function stableHash(value) {
  let hash = 0;
  for (const char of String(value || '')) {
    hash = ((hash << 5) - hash) + char.charCodeAt(0);
    hash |= 0;
  }
  return Math.abs(hash);
}

function pseudoCoordinate(seed, min, max) {
  const ratio = (seed % 10000) / 10000;
  return Number((min + ((max - min) * ratio)).toFixed(6));
}

function getCityCoordinates(city) {
  const normalized = normalizeCityName(city);
  const alias = ALIAS_MAP[normalized];
  return CITY_COORDINATES[normalized] || CITY_COORDINATES[alias] || null;
}

function getCoordinatesForCity(city) {
  const named = getCityCoordinates(city);
  if (named) {
    return named;
  }

  // Unknown dataset stops are usually local boarding points. Keep fallback
  // coordinates inside Karnataka instead of sending the map across India.
  const seed = stableHash(city);
  return {
    lat: pseudoCoordinate(seed, 11.6, 16.2),
    lng: pseudoCoordinate(seed * 3, 74.0, 78.6),
  };
}

